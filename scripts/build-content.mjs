// Generates supabase/migrations/0005_content_map.sql and 00NN_content_missions_*.sql from content/*.mjs
// Run: npm run content
import { writeFileSync, readdirSync, unlinkSync } from 'node:fs';
import { LOCATIONS, EDGES, ITEMS, BUILDINGS, RETIRED } from '../content/map.mjs';
import { building } from '../content/campus.mjs';
import { buildMissions } from '../content/missions.mjs';
import { buildMissions2 } from '../content/missions2.mjs';
import { buildMissions3 } from '../content/missions3.mjs';

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`;
const json = (o) => `${q(JSON.stringify(o))}::jsonb`;

const missions = buildMissions();
const missions2 = buildMissions2().map((m) => ({ ...m }));
for (const m of missions2) if (missions.find((x) => x.id === m.id)) throw new Error(`duplicate template id ${m.id}`);
const missions3 = buildMissions3();
for (const m of missions3) if ([...missions, ...missions2].find((x) => x.id === m.id)) throw new Error(`duplicate template id ${m.id}`);
const missionInsert = (missions) => `insert into mission_templates(id, family, kind, title, category, difficulty, tags, objective, clues, parts, relay,
  attempts, time_limit, hint, explanation, points, coins, status) values
${missions.map((m) => `(${q(m.id)}, ${q(m.family)}, ${q(m.kind)}, ${q(m.title)}, ${q(m.category)}, ${m.difficulty}, ${arr(m.tags)}, ${q(m.objective)}, ${json(m.clues)}, ${json(m.parts)}, ${m.relay}, ${m.attempts}, ${m.time_limit}, ${q(m.hint)}, ${q(m.explanation)}, ${m.points ?? 'null'}, ${m.coins}, ${q(m.status)})`).join(',\n')}
on conflict (id) do update set family = excluded.family, kind = excluded.kind, title = excluded.title, category = excluded.category,
  difficulty = excluded.difficulty, tags = excluded.tags, objective = excluded.objective, clues = excluded.clues, parts = excluded.parts,
  relay = excluded.relay, attempts = excluded.attempts, time_limit = excluded.time_limit, hint = excluded.hint,
  explanation = excluded.explanation, points = excluded.points, coins = excluded.coins, status = excluded.status,
  version = case when mission_templates.clues is distinct from excluded.clues or mission_templates.parts is distinct from excluded.parts
                 then mission_templates.version + 1 else mission_templates.version end,
  updated_at = now();
`;
const ids = new Set(LOCATIONS.map((l) => l[0]));
for (const [a, b] of EDGES) {
  if (!ids.has(a) || !ids.has(b)) throw new Error(`edge references unknown location ${a}-${b}`);
}

// The original map (0005) is frozen; the v4 campus (buildings, floors) lands in 0501, after the 0500 schema.
let sql = `-- GENERATED by scripts/build-content.mjs — edit content/map.mjs / content/campus.mjs and re-run \`npm run content\`.
-- Campus v4: ${BUILDINGS.length} buildings with floors, ${LOCATIONS.length} places, ${EDGES.length} links, item catalogue.

insert into buildings(id, name, x0, y0, x1, y1, floors, stair_x, stair_y, door_x, door_y, style) values
${BUILDINGS.map(([id]) => { const b = building(id); return `(${q(b.id)}, ${q(b.name)}, ${b.x0}, ${b.y0}, ${b.x1}, ${b.y1}, ${b.floors}, ${b.stairs[0].toFixed(4)}, ${b.stairs[1].toFixed(4)}, ${b.door[0].toFixed(4)}, ${b.door[1].toFixed(4)}, ${q(b.style)})`; }).join(',\n')}
on conflict (id) do update set name = excluded.name, x0 = excluded.x0, y0 = excluded.y0, x1 = excluded.x1, y1 = excluded.y1,
  floors = excluded.floors, stair_x = excluded.stair_x, stair_y = excluded.stair_y, door_x = excluded.door_x, door_y = excluded.door_y, style = excluded.style;

insert into locations(id, name, building, floor, x, y, kind, collapse_stage, risk, reward, tags, drop_zone, loot, level, enabled) values
${LOCATIONS.map(([id, name, building, floor, x, y, kind, collapse, risk, reward, tags, drop, loot, level]) =>
  `(${q(id)}, ${q(name)}, ${q(building)}, ${q(floor)}, ${x}, ${y}, ${q(kind)}, ${collapse}, ${risk}, ${q(reward)}, ${arr(tags)}, ${drop}, ${arr(loot)}, ${level}, true)`).join(',\n')}
on conflict (id) do update set name = excluded.name, building = excluded.building, floor = excluded.floor, x = excluded.x,
  y = excluded.y, kind = excluded.kind, collapse_stage = excluded.collapse_stage, risk = excluded.risk, reward = excluded.reward,
  tags = excluded.tags, drop_zone = excluded.drop_zone, loot = excluded.loot, level = excluded.level, enabled = true;

-- places that no longer exist stay in the table (old games point at them) but are switched off
update locations set enabled = false where id in (${RETIRED.map(q).join(', ')});

delete from edges where not exists (select 1 from (values ${EDGES.map(([a, b]) => `(${q(a)}, ${q(b)})`).join(', ')}) v(a, b) where v.a = edges.a and v.b = edges.b);
insert into edges(a, b, seconds) values
${EDGES.map(([a, b, s]) => `(${q(a)}, ${q(b)}, ${s})`).join(',\n')}
on conflict (a, b) do update set seconds = excluded.seconds;

insert into items(id, name, kind, description, params, price) values
${ITEMS.map(([id, name, kind, desc, params, price]) => `(${q(id)}, ${q(name)}, ${q(kind)}, ${q(desc)}, ${json(params)}, ${price})`).join(',\n')}
on conflict (id) do update set name = excluded.name, kind = excluded.kind, description = excluded.description,
  params = excluded.params, price = excluded.price;

-- squads already standing somewhere keep a consistent storey
update teams t set level = l.level, bldg = case when l.level > 0 then l.building end from locations l where l.id = t.location_id and t.level <> l.level;
`;

const migDir = new URL('../supabase/migrations/', import.meta.url);
for (const f of readdirSync(migDir)) if (/^00(0[6-9]|[1-9]\d)_content/.test(f)) unlinkSync(new URL(f, migDir));
for (const f of readdirSync(migDir)) if (/^05\d\d_content/.test(f)) unlinkSync(new URL(f, migDir));
writeFileSync(new URL('0501_content_map_v4.sql', migDir), sql);
// missions in chunks so each file stays well under the Supabase SQL Editor's 100k-character limit
const CHUNK = 8;
for (let i = 0; i * CHUNK < missions.length; i++) {
  const batch = missions.slice(i * CHUNK, (i + 1) * CHUNK);
  const msql = `-- GENERATED by scripts/build-content.mjs — mission library part ${i + 1}.\n` + missionInsert(batch);
  writeFileSync(new URL(`00${String(6 + i).padStart(2, '0')}_content_missions_${i + 1}.sql`, migDir), msql);
}
// Pack 2 lands as 03xx migrations (after 0300) so existing databases get the latest version through the upgrade bundle.
for (const f of readdirSync(migDir)) if (/^0[23]\d\d_content_v2/.test(f)) unlinkSync(new URL(f, migDir));
const CHUNK2 = 4; // small statements: the upgrade bundle keeps every paste under 7k characters
for (let i = 0; i * CHUNK2 < missions2.length; i++) {
  const batch = missions2.slice(i * CHUNK2, (i + 1) * CHUNK2);
  const msql = `-- GENERATED by scripts/build-content.mjs — challenge pack 2 (picture riddles, riddles, emoji movies, tech quick-fire, mini sudoku, Fruit Slash), part ${i + 1}.\n` + missionInsert(batch);
  writeFileSync(new URL(`03${String(10 + i).padStart(2, '0')}_content_v2_${i + 1}.sql`, migDir), msql);
}
const CHUNK3 = 6;
for (let i = 0; i * CHUNK3 < missions3.length; i++) {
  const batch = missions3.slice(i * CHUNK3, (i + 1) * CHUNK3);
  const msql = `-- GENERATED by scripts/build-content.mjs — challenge pack 3 (bottle shoot, memory cards, poker, blackjack, card sharp, safe cracker, morse, scramble, maths, sequences, flags, odd one out, clocks), part ${i + 1}.\n` + missionInsert(batch);
  writeFileSync(new URL(`05${String(10 + i).padStart(2, '0')}_content_v3_${i + 1}.sql`, migDir), msql);
}
console.log(`Pack 3: ${missions3.length} templates`);
console.log(`Pack 2: ${missions2.length} templates`, missions2.reduce((m, t) => ({ ...m, [t.family]: (m[t.family] || 0) + 1 }), {}));
const byKind = missions.reduce((m, t) => ({ ...m, [t.kind]: (m[t.kind] || 0) + 1 }), {});
console.log(`Wrote content migrations — ${LOCATIONS.length} locations, ${EDGES.length} edges, ${ITEMS.length} items, ${missions.length} missions`, byKind);
